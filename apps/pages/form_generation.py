def make_generation_history_table(rows):
    header = html.Tr([
        html.Th("Version"),
        html.Th("Generated On"),
        html.Th("Generated By"),
        html.Th("Status"),
        html.Th("Actions"),
    ])
    table_rows = []
    for r in rows:
        action_links = []
        for i, action in enumerate(r["actions"]):
            if i > 0:
                action_links.append(html.Span(" ", style={"margin": "0 2px"}))
            action_links.append(html.A(action, href="#", className="action-link"))
        table_rows.append(
            html.Tr([
                html.Td(r["version"], className="cell-primary"),
                html.Td(r["generated_on"]),
                html.Td(r["generated_by"]),
                html.Td(html.Span(r["status"], className=f"status-badge {r['status_badge']}")),
                html.Td(action_links),
            ])
        )
    return html.Div(
        html.Table(
            [html.Thead(header), html.Tbody(table_rows)],
            className="data-table",
        ),
        className="data-table-wrap",
    )


