@callback(
    Output("gen-tab", "data"),
    Output("tab-adv", "className"),
    Output("tab-pf", "className"),
    Input("tab-adv", "n_clicks"),
    Input("tab-pf", "n_clicks"),
    State("gen-tab", "data"),
    prevent_initial_call=True,
)
def switch_tab(adv_clicks, pf_clicks, current_tab):
    from dash import ctx
    triggered = ctx.triggered_id
    if triggered == "tab-adv":
        return "ADV", "tab-item tab-active", "tab-item"
    elif triggered == "tab-pf":
        return "PF", "tab-item", "tab-item tab-active"
    return current_tab, "tab-item tab-active", "tab-item"


@callback(
    Output("gen-tab-content", "children"),
    Input("gen-tab", "data"),
)
def render_tab_content(tab):
    if tab == "PF":
        return make_pf_tab()
    return make_adv_tab()
